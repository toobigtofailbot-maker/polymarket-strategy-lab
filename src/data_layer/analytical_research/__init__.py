"""WP167 analytical research foundation package.

Local, offline, read-only-against-canonical, derived-data analytical plane over
the merged deterministic point-in-time evidence system. Canonical SQLite records
and manifests remain the sole integrity authority; Parquet produced here is
derived analytical materialization only, and external pmxt v2 history is external
research evidence only. This package has NO execution authority: no network, no
downloader, no NautilusTrader, no scheduler, no strategy, no paper/live behavior.
"""

